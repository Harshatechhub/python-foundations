# Python Lists
# Day 6 - Python Foundations

fruits = ["apple", "banana", "orange", "mango"]

# Accessing elements
print("First fruit:", fruits[0])
print("Last fruit:", fruits[-1])

# Adding an element
fruits.append("grape")

# Removing an element
fruits.remove("banana")

# Updating an element
fruits[0] = "watermelon"

# Displaying the list
print("Updated fruits:", fruits)

# Looping through a list
for fruit in fruits:
    print(fruit)
